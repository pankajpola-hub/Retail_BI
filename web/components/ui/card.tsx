import * as React from "react";
import { cn } from "@/lib/utils";

/** shadcn/ui-shaped Card family, authored against the app's existing surface/border/ink tokens — see button.tsx's header comment for why no parallel token set was introduced. */
export const Card = React.forwardRef<HTMLDivElement, React.HTMLAttributes<HTMLDivElement>>(
  ({ className, ...props }, ref) => (
    <div ref={ref} className={cn("rounded-lg border border-line-soft bg-surface shadow-sm", className)} {...props} />
  )
);
Card.displayName = "Card";

